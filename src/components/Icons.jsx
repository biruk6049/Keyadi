/* Category icon resolver */
export function CategoryIcon({ iconKey, size = 14, color = "currentColor" }) {
  switch (iconKey) {
    case 'food': return <FoodIcon size={size} color={color} />
    case 'cafe': return <CafeIcon size={size} color={color} />
    case 'gas': return <FuelIcon size={size} color={color} />
    case 'pharmacy': return <PharmacyIcon size={size} color={color} />
    case 'shop': return <ShopIcon size={size} color={color} />
    case 'atm': return <AtmIcon size={size} color={color} />
    case 'parking': return <ParkingIcon size={size} color={color} />
    case 'hotel': return <HotelIcon size={size} color={color} />
    case 'hospital': return <HospitalIcon size={size} color={color} />
    case 'school': return <SchoolIcon size={size} color={color} />
    case 'worship': return <WorshipIcon size={size} color={color} />
    case 'supermarket': return <MarketIcon size={size} color={color} />
    case 'hardware': return <HardwareIcon size={size} color={color} />
    default: return <MapPinIcon size={size} color={color} />
  }
}

